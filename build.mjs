/** Build one offline HTML file, without dependencies or a local web server. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const directory = dirname(fileURLToPath(import.meta.url));
const read = (name) => readFile(join(directory, name), 'utf8');
const dataURL = (mime, text) => `data:${mime};charset=utf-8;base64,${Buffer.from(text, 'utf8').toString('base64')}`;

const [template, stylesheet, physics, measurements, appSource, protocol, paths, pathViewSource, lyapunov, lyapunovViewSource] = await Promise.all([
  read('index.html'), read('style.css'), read('physics.js'),
  read('measurements.js'), read('app.js'), read('README.md'), read('paths.js'), read('path-view.js'),
  read('lyapunov.js'), read('lyapunov-view.js'),
]);

// Preserve separate module scopes and exports. Only module URLs are rewritten;
// no regex stripping of JavaScript syntax or runtime symbol renaming is needed.
let pathImportCount = 0;
const pathView = pathViewSource.replace(/(\bfrom\s*)(['"])(\.\/paths\.js)\2/g,
  (_match, prefix, quote) => { pathImportCount += 1; return `${prefix}${quote}${dataURL('text/javascript', paths)}${quote}`; });
if (pathImportCount !== 1) throw new Error('Expected one paths.js import in path-view.js.');
let lyapunovImportCount = 0;
const lyapunovDependencies = new Map([['./lyapunov.js',lyapunov],['./measurements.js',measurements]]);
const lyapunovView = lyapunovViewSource.replace(/(\bfrom\s*)(['"])(\.\/(?:lyapunov|measurements)\.js)\2/g,
  (_match,prefix,quote,specifier) => { lyapunovImportCount++; return `${prefix}${quote}${dataURL('text/javascript',lyapunovDependencies.get(specifier))}${quote}`; });
if(lyapunovImportCount !== 2) throw new Error('Expected both analysis dependencies in lyapunov-view.js.');
const embeddedModules = new Map([
  ['./physics.js', dataURL('text/javascript', physics)],
  ['./measurements.js', dataURL('text/javascript', measurements)],
  ['./path-view.js', dataURL('text/javascript', pathView)],
  ['./lyapunov-view.js', dataURL('text/javascript', lyapunovView)],
]);
let importCount = 0;
const app = appSource.replace(/(\bfrom\s*)(['"])(\.\/(?:physics|measurements|path-view|lyapunov-view)\.js)\2/g,
  (_match, prefix, quote, specifier) => {
    importCount += 1;
    return `${prefix}${quote}${embeddedModules.get(specifier)}${quote}`;
  });
if (importCount !== embeddedModules.size) {
  throw new Error(`Expected one app import per embedded module; found ${importCount}. Update build.mjs for the changed imports.`);
}

function replaceExactlyOnce(source, pattern, replacement, description) {
  let count = 0;
  const result = source.replace(pattern, (...args) => {
    count += 1;
    return typeof replacement === 'function' ? replacement(...args) : replacement;
  });
  if (count !== 1) throw new Error(`Expected exactly one ${description}; found ${count}.`);
  return result;
}

// Remove the empty placeholder import; no network fonts or CSS are necessary.
const css = stylesheet.replace(/@import\s+url\(['"]?data:text\/css,['"]?\)\s*;\s*/g, '');
if (/<\/style/i.test(css)) throw new Error('Stylesheet contains a closing HTML style tag.');
let html = replaceExactlyOnce(template,
  /<link\b[^>]*\bhref=['"](?:\.\/)?style\.css['"][^>]*>/g,
  `<style>\n${css}\n</style>`, 'stylesheet link');
html = replaceExactlyOnce(html,
  /<script\b(?=[^>]*\btype=['"]module['"])(?=[^>]*\bsrc=['"](?:\.\/)?app\.js['"])[^>]*>\s*<\/script>/g,
  `<script>window.STANDALONE = true;</script>\n<script type="module" src="${dataURL('text/javascript', app)}"></script>`,
  'app module script');
html = replaceExactlyOnce(html,
  /<a\b(?=[^>]*\bid=['"]protocol-link['"])[^>]*>/g,
  (anchor) => {
    if (!/\bhref=['"]README\.md['"]/.test(anchor)) throw new Error('Unexpected protocol link target.');
    return anchor.replace(/\bhref=['"]README\.md['"]/, `href="${dataURL('text/plain', protocol)}" download="dubbele-slinger-meetprotocol.md"`)
      .replace(/\s+target=['"]_blank['"]/, '');
  }, 'measurement protocol link');
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by node build.mjs. Edit the modular source files and rebuild. -->');

const outputPath = join(directory, 'standalone.html');
await writeFile(outputPath, html, 'utf8');
console.log(`Built standalone.html (${Buffer.byteLength(html, 'utf8')} bytes). Open this file directly in a modern browser.`);
